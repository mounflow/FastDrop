-- 0002: 设备忽略标记。
--
-- 产品语义：用户主动执行的结果必须符合其意愿——"删除设备" = 双向断开 +
-- 清除配对记录（devices/sessions 行）+ 不自动恢复。因此被删除的设备在此
-- 打上 ignored_at 标记：
--   * 自动回连（反向配对）跳过它，不会"删了又回来"；
--   * 它再次主动配对时不静默接受，需本机用户显式确认；
--   * 用户主动重新配对会清除该标记（不是永久黑名单）。
--
-- 注意：本标记只影响"配对凭证"，与传输记录（transfers / transfer_files /
-- file_chunk_states）完全无关——删除设备永不触碰传输记录。
ALTER TABLE devices ADD COLUMN ignored_at INTEGER;
